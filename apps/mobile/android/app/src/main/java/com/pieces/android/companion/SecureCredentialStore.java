package com.pieces.android.companion;

import android.content.Context;
import android.content.SharedPreferences;
import android.security.keystore.KeyGenParameterSpec;
import android.security.keystore.KeyProperties;
import android.util.Log;

import java.nio.charset.StandardCharsets;
import java.security.GeneralSecurityException;
import java.security.KeyStore;
import java.security.SecureRandom;
import java.util.Arrays;
import java.util.Base64;

import javax.crypto.Cipher;
import javax.crypto.KeyGenerator;
import javax.crypto.SecretKey;
import javax.crypto.spec.GCMParameterSpec;

/**
 * Bearer-token storage backed by a non-exportable Android Keystore AES-256 key (separate from the
 * approval signing key). Each value is sealed with AES/GCM/NoPadding, a provider-generated IV, a
 * 128-bit tag and the credential name as AAD, and stored as {@code base64(version(1) | iv(12) | ct+tag)}
 * in app-private SharedPreferences.
 *
 * Reads fail closed: a missing, malformed, tampered or key-invalidated entry yields {@code null},
 * never a partial or plaintext value. There is no plaintext fallback.
 */
final class SecureCredentialStore {

    private static final String TAG = "SecureCredentialStore";
    static final String KEY_ALIAS = "exocortex_credential_key_v1";
    static final String PREFS = "exocortex_secure_credentials";
    private static final String ANDROID_KEYSTORE = "AndroidKeyStore";
    private static final byte VERSION = 1;
    private static final int IV_LEN = 12;
    private static final int TAG_BITS = 128;

    private SecureCredentialStore() {}

    /** Returns the decrypted value, or null if absent or unreadable (tampered, wrong key, malformed). */
    static synchronized String get(Context context, String name) {
        SharedPreferences prefs = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE);
        String envelope = prefs.getString(name, null);
        if (envelope == null) return null;
        try {
            return open(loadKey(false), name, envelope);
        } catch (Exception e) {
            Log.w(TAG, "credential unreadable: " + name);
            return null;
        }
    }

    static synchronized void set(Context context, String name, String value) throws GeneralSecurityException {
        String envelope;
        try {
            envelope = seal(loadKey(true), name, value);
        } catch (GeneralSecurityException e) {
            // The key can be invalidated (e.g. secure lock screen removed). Old entries are unreadable
            // anyway, so replace the key once and retry rather than leaving the app unable to pair.
            deleteKey();
            envelope = seal(loadKey(true), name, value);
        }
        boolean ok = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
            .edit().putString(name, envelope).commit();
        if (!ok) throw new GeneralSecurityException("credential write failed");
    }

    static synchronized void remove(Context context, String name) {
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).edit().remove(name).commit();
    }

    /** Package-private for tests: encrypt with an explicit key. */
    static String seal(SecretKey key, String name, String value) throws GeneralSecurityException {
        Cipher cipher = Cipher.getInstance("AES/GCM/NoPadding");
        cipher.init(Cipher.ENCRYPT_MODE, key); // IV is generated by the provider, fresh every call
        cipher.updateAAD(name.getBytes(StandardCharsets.UTF_8));
        byte[] iv = cipher.getIV();
        if (iv == null || iv.length != IV_LEN) throw new GeneralSecurityException("unexpected IV length");
        byte[] ct = cipher.doFinal(value.getBytes(StandardCharsets.UTF_8));
        byte[] out = new byte[1 + IV_LEN + ct.length];
        out[0] = VERSION;
        System.arraycopy(iv, 0, out, 1, IV_LEN);
        System.arraycopy(ct, 0, out, 1 + IV_LEN, ct.length);
        return Base64.getEncoder().encodeToString(out);
    }

    /** Package-private for tests: returns null for anything that does not authenticate. */
    static String open(SecretKey key, String name, String envelope) {
        try {
            byte[] raw = Base64.getDecoder().decode(envelope);
            if (raw.length < 1 + IV_LEN + TAG_BITS / 8 || raw[0] != VERSION) return null;
            Cipher cipher = Cipher.getInstance("AES/GCM/NoPadding");
            cipher.init(Cipher.DECRYPT_MODE, key, new GCMParameterSpec(TAG_BITS, Arrays.copyOfRange(raw, 1, 1 + IV_LEN)));
            cipher.updateAAD(name.getBytes(StandardCharsets.UTF_8));
            return new String(cipher.doFinal(raw, 1 + IV_LEN, raw.length - 1 - IV_LEN), StandardCharsets.UTF_8);
        } catch (Exception e) {
            return null;
        }
    }

    private static SecretKey loadKey(boolean createIfMissing) throws GeneralSecurityException {
        try {
            KeyStore ks = KeyStore.getInstance(ANDROID_KEYSTORE);
            ks.load(null);
            if (ks.containsAlias(KEY_ALIAS)) {
                return (SecretKey) ks.getKey(KEY_ALIAS, null);
            }
            if (!createIfMissing) throw new GeneralSecurityException("credential key not present");
            KeyGenerator kg = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE);
            kg.init(new KeyGenParameterSpec.Builder(KEY_ALIAS, KeyProperties.PURPOSE_ENCRYPT | KeyProperties.PURPOSE_DECRYPT)
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(256)
                .setRandomizedEncryptionRequired(true)
                .build());
            return kg.generateKey();
        } catch (GeneralSecurityException e) {
            throw e;
        } catch (Exception e) {
            throw new GeneralSecurityException(e);
        }
    }

    private static void deleteKey() {
        try {
            KeyStore ks = KeyStore.getInstance(ANDROID_KEYSTORE);
            ks.load(null);
            if (ks.containsAlias(KEY_ALIAS)) ks.deleteEntry(KEY_ALIAS);
        } catch (Exception ignored) {
            // best effort; the retry in set() will surface a real failure
        }
    }
}
